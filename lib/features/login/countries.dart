Country countryByIso(String? iso) => countries.firstWhere(
  (c) => c.iso == (iso ?? '').toUpperCase(),
  orElse: () => countries.first,
);

/// Best-effort guess from the phone's locale (no permission needed).
Country detectCountry() {
  final loc = PlatformDispatcher.instance.locale;
  // Arabic UI with a non-Arab region (e.g. en_GB fallback) -> Egypt.
  final iso = loc.countryCode;
  if ((iso == null || iso.isEmpty) && loc.languageCode == 'ar') return countryByIso('EG');
  return countryByIso(iso);
}

class PhoneParse {
  const PhoneParse(this.e164, this.valid, this.national);
  final String e164;
  final bool valid;
  final String national;
}

/// Normalises what the user typed (with/without a leading 0, +, 00 or the
/// dial code) into an E.164 number for [c].
PhoneParse normalizePhone(Country c, String raw) {
  var d = raw.replaceAll(RegExp(r'[^0-9+]'), '');
  final plus = d.startsWith('+');
  d = d.replaceAll('+', '');
  if (d.startsWith('00')) d = d.substring(2);
  var national = d;
  if ((plus || raw.trim().startsWith('00')) && d.startsWith(c.dial)) {
    national = d.substring(c.dial.length);
  } else if (d.startsWith(c.dial) && d.length > c.max) {
    // typed the dial code without + (e.g. 20 10…)
    national = d.substring(c.dial.length);
  }
  if (!c.keepZero) national = national.replaceFirst(RegExp(r'^0+'), '');
  final ok = national.length >= c.min && national.length <= c.max;
  return PhoneParse('+${c.dial}$national', ok, national);
}
